import React, { useState } from 'react';
import {
  View,
  Text,
  StyleSheet,
  TouchableOpacity,
  Modal,
  ScrollView,
  Share,
  Alert,
  ActivityIndicator,
} from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { useTheme } from '../../hooks/useTheme';
import * as Sharing from 'expo-sharing';
import * as FileSystem from 'expo-file-system';

/**
 * ShareSolution Component
 * Provides sharing options for solutions
 */
const ShareSolution = ({ solution, problem, visible, onClose }) => {
  const { colors } = useTheme();
  const styles = createStyles(colors);
  const [isSharing, setIsSharing] = useState(false);

  const generateSolutionText = () => {
    if (!solution) return '';

    let text = `📐 Mathematics Solution\n\n`;
    text += `Problem: ${problem?.title || 'Math Problem'}\n`;
    text += `Category: ${problem?.category || 'General'}\n`;
    text += `Difficulty: ${problem?.difficulty || 'Medium'}\n\n`;
    text += `━━━━━━━━━━━━━━━━━━━━━\n\n`;

    if (solution.steps && solution.steps.length > 0) {
      text += `Step-by-Step Solution:\n\n`;
      solution.steps.forEach((step, index) => {
        text += `Step ${step.stepNumber}: ${step.description}\n`;
        if (step.formula) {
          text += `  ${step.formula}\n`;
        }
        if (step.explanation) {
          text += `  ${step.explanation}\n\n`;
        }
      });
    }

    if (solution.finalAnswer) {
      text += `━━━━━━━━━━━━━━━━━━━━━\n\n`;
      text += `✅ Final Answer: ${solution.finalAnswer}\n`;
    }

    if (solution.confidence) {
      text += `\nConfidence: ${Math.round(solution.confidence * 100)}%\n`;
    }

    text += `\nGenerated by Mathematics Solver App`;

    return text;
  };

  const handleShareText = async () => {
    try {
      setIsSharing(true);
      const shareText = generateSolutionText();

      await Share.share({
        message: shareText,
        title: `Solution: ${problem?.title || 'Math Problem'}`,
      });

      onClose();
    } catch (error) {
      console.error('Error sharing:', error);
      Alert.alert('Error', 'Failed to share solution');
    } finally {
      setIsSharing(false);
    }
  };

  const handleShareImage = async () => {
    try {
      setIsSharing(true);
      // In a real implementation, you'd capture the solution view as an image
      // using react-native-view-shot or similar library
      Alert.alert(
        'Share as Image',
        'This feature will capture the solution as an image. Implementation requires react-native-view-shot library.',
        [{ text: 'OK' }]
      );
      onClose();
    } catch (error) {
      console.error('Error sharing image:', error);
      Alert.alert('Error', 'Failed to share solution as image');
    } finally {
      setIsSharing(false);
    }
  };

  const handleCopyLink = async () => {
    try {
      // Generate a shareable link (in production, this would be a real URL)
      const shareableLink = `https://mathsolver.app/solution/${solution?.id}`;
      
      await Share.share({
        message: `Check out this solution: ${shareableLink}`,
        title: 'Mathematics Solution',
      });
      
      onClose();
    } catch (error) {
      console.error('Error sharing link:', error);
      Alert.alert('Error', 'Failed to share link');
    }
  };

  const handleExportText = async () => {
    try {
      setIsSharing(true);
      const shareText = generateSolutionText();
      
      // Save to file
      const fileName = `solution_${solution?.id || 'unknown'}.txt`;
      const filePath = `${FileSystem.documentDirectory}${fileName}`;
      
      await FileSystem.writeAsStringAsync(filePath, shareText);
      
      // Share the file
      if (await Sharing.isAvailableAsync()) {
        await Sharing.shareAsync(filePath);
      } else {
        Alert.alert('Saved', `Solution saved to ${filePath}`);
      }
      
      onClose();
    } catch (error) {
      console.error('Error exporting:', error);
      Alert.alert('Error', 'Failed to export solution');
    } finally {
      setIsSharing(false);
    }
  };

  return (
    <Modal
      visible={visible}
      animationType="slide"
      transparent={true}
      onRequestClose={onClose}
    >
      <View style={styles.overlay}>
        <View style={styles.backdrop} onTouchEnd={onClose} />
        
        <View style={styles.container}>
          <View style={styles.header}>
            <Text style={styles.title}>Share Solution</Text>
            <TouchableOpacity onPress={onClose} style={styles.closeButton}>
              <Ionicons name="close" size={24} color={colors.text} />
            </TouchableOpacity>
          </View>

          {isSharing && (
            <View style={styles.loadingContainer}>
              <ActivityIndicator size="large" color={colors.primary} />
              <Text style={styles.loadingText}>Preparing to share...</Text>
            </View>
          )}

          <ScrollView style={styles.optionsContainer}>
            <TouchableOpacity
              style={styles.option}
              onPress={handleShareText}
              disabled={isSharing}
            >
              <View style={[styles.optionIcon, { backgroundColor: colors.primary }]}>
                <Ionicons name="share" size={24} color={colors.onPrimary} />
              </View>
              <View style={styles.optionContent}>
                <Text style={styles.optionTitle}>Share as Text</Text>
                <Text style={styles.optionDescription}>
                  Share the complete solution via any app
                </Text>
              </View>
              <Ionicons name="chevron-forward" size={24} color={colors.textSecondary} />
            </TouchableOpacity>

            <TouchableOpacity
              style={styles.option}
              onPress={handleShareImage}
              disabled={isSharing}
            >
              <View style={[styles.optionIcon, { backgroundColor: colors.success }]}>
                <Ionicons name="image" size={24} color={colors.onPrimary} />
              </View>
              <View style={styles.optionContent}>
                <Text style={styles.optionTitle}>Share as Image</Text>
                <Text style={styles.optionDescription}>
                  Capture and share as an image
                </Text>
              </View>
              <Ionicons name="chevron-forward" size={24} color={colors.textSecondary} />
            </TouchableOpacity>

            <TouchableOpacity
              style={styles.option}
              onPress={handleCopyLink}
              disabled={isSharing}
            >
              <View style={[styles.optionIcon, { backgroundColor: colors.warning }]}>
                <Ionicons name="link" size={24} color={colors.onPrimary} />
              </View>
              <View style={styles.optionContent}>
                <Text style={styles.optionTitle}>Share Link</Text>
                <Text style={styles.optionDescription}>
                  Generate and share a link to this solution
                </Text>
              </View>
              <Ionicons name="chevron-forward" size={24} color={colors.textSecondary} />
            </TouchableOpacity>

            <TouchableOpacity
              style={styles.option}
              onPress={handleExportText}
              disabled={isSharing}
            >
              <View style={[styles.optionIcon, { backgroundColor: colors.secondary }]}>
                <Ionicons name="download" size={24} color={colors.onPrimary} />
              </View>
              <View style={styles.optionContent}>
                <Text style={styles.optionTitle}>Export to File</Text>
                <Text style={styles.optionDescription}>
                  Save solution as a text file
                </Text>
              </View>
              <Ionicons name="chevron-forward" size={24} color={colors.textSecondary} />
            </TouchableOpacity>
          </ScrollView>

          <View style={styles.solutionInfo}>
            <Text style={styles.infoLabel}>Solution:</Text>
            <Text style={styles.infoValue} numberOfLines={1}>
              {problem?.title || 'Math Problem'}
            </Text>
            <Text style={styles.infoSteps}>
              {solution?.steps?.length || 0} steps •{' '}
              {Math.round((solution?.confidence || 0) * 100)}% confidence
            </Text>
          </View>
        </View>
      </View>
    </Modal>
  );
};

