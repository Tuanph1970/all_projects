"""
Overbought/Oversold Indicators as Exit Signals — Chapter 10, Concept 4
======================================================================
Uses oscillator readings (RSI, stochastics, momentum) as signals
to liquidate profitable positions.

Schwager's critical insight: "The approach will usually work well
when the market is in a trading range, but will fail miserably
during strong trending phases."

This module provides:
  - RSI calculation and OB/OS exit signal generation
  - Regime detection (trending vs. range-bound)
  - Adaptive threshold logic
  - Signal quality assessment
"""

import pandas as pd
import numpy as np
from dataclasses import dataclass, field
from typing import List, Tuple, Optional, Literal


@dataclass
class OBOSExitSignal:
    """An exit signal generated by an overbought/oversold indicator."""
    index: int
    price: float
    indicator_value: float
    signal_type: str  # 'exit_long' (overbought) or 'exit_short' (oversold)
    threshold: float
    indicator_name: str = "RSI"

    @property
    def description(self) -> str:
        condition = "overbought" if self.signal_type == 'exit_long' else "oversold"
        action = "liquidate long" if self.signal_type == 'exit_long' else "liquidate short"
        return (f"{self.indicator_name}={self.indicator_value:.1f} → "
                f"{condition} → {action} at {self.price:.2f}")


@dataclass
class ExitSignalAssessment:
    """
    Quality assessment of OB/OS exit signals for a given period.
    
    Evaluates whether the market regime is suitable for
    oscillator-based exits.
    """
    regime: str  # 'trading_range', 'trending', 'mixed'
    total_signals: int
    premature_exits: int  # Signals followed by continued trend
    good_exits: int  # Signals near actual turning points
    regime_warning: str = ""

    @property
    def hit_rate(self) -> float:
        if self.total_signals == 0:
            return 0.0
        return self.good_exits / self.total_signals

    @property
    def is_suitable(self) -> bool:
        """Schwager: oscillators work in ranges, fail in trends."""
        return self.regime in ('trading_range', 'mixed')


def calculate_rsi(
    closes: pd.Series,
    period: int = 14
) -> pd.Series:
    """
    Calculate the Relative Strength Index (RSI).
    
    RSI = 100 - 100 / (1 + RS)
    where RS = average gain / average loss over N periods.
    
    Parameters
    ----------
    closes : pd.Series
        Closing prices.
    period : int
        RSI lookback period (default 14, Wilder's original).
        
    Returns
    -------
    pd.Series
        RSI values (0-100).
    """
    delta = closes.diff()
    gains = delta.where(delta > 0, 0.0)
    losses = (-delta).where(delta < 0, 0.0)
    
    # Wilder's smoothing (exponential)
    avg_gain = gains.ewm(alpha=1/period, min_periods=period, adjust=False).mean()
    avg_loss = losses.ewm(alpha=1/period, min_periods=period, adjust=False).mean()
    
    rs = avg_gain / avg_loss.replace(0, np.nan)
    rsi = 100 - 100 / (1 + rs)
    return rsi.fillna(50)


def generate_exit_signals(
    closes: pd.Series,
    rsi: pd.Series,
    ob_threshold: float = 70.0,
    os_threshold: float = 30.0
) -> List[OBOSExitSignal]:
    """
    Generate position exit signals from RSI OB/OS crossings.
    
    Schwager's usage: OB crossing = exit LONG (not initiate short).
    OS crossing = exit SHORT (not initiate long).
    
    Parameters
    ----------
    closes : pd.Series
        Closing prices.
    rsi : pd.Series
        Pre-calculated RSI values.
    ob_threshold : float
        Overbought level (default 70). Higher = fewer but later signals.
    os_threshold : float
        Oversold level (default 30). Lower = fewer but later signals.
        
    Returns
    -------
    list of OBOSExitSignal
    """
    signals = []
    
    for i in range(1, len(rsi)):
        # OB crossing: RSI crosses above threshold → exit long
        if rsi.iloc[i] >= ob_threshold and rsi.iloc[i-1] < ob_threshold:
            signals.append(OBOSExitSignal(
                index=i,
                price=float(closes.iloc[i]),
                indicator_value=float(rsi.iloc[i]),
                signal_type='exit_long',
                threshold=ob_threshold,
            ))
        # OS crossing: RSI crosses below threshold → exit short
        elif rsi.iloc[i] <= os_threshold and rsi.iloc[i-1] > os_threshold:
            signals.append(OBOSExitSignal(
                index=i,
                price=float(closes.iloc[i]),
                indicator_value=float(rsi.iloc[i]),
                signal_type='exit_short',
                threshold=os_threshold,
            ))
    
    return signals


def detect_regime(
    closes: pd.Series,
    lookback: int = 50,
    trend_threshold: float = 0.15
) -> str:
    """
    Classify market regime as trending or range-bound.
    
    Uses the ratio of net price change to total path length.
    Trending markets have high efficiency ratios (price moves
    far relative to path traveled). Range-bound markets have
    low efficiency ratios (price goes back and forth).
    
    Parameters
    ----------
    closes : pd.Series
        Closing prices.
    lookback : int
        Period to evaluate.
    trend_threshold : float
        Efficiency ratio above this = trending.
        
    Returns
    -------
    str
        'trending', 'trading_range', or 'mixed'
    """
    if len(closes) < lookback:
        return 'mixed'
    
    recent = closes.iloc[-lookback:]
    net_change = abs(float(recent.iloc[-1] - recent.iloc[0]))
    total_path = float(recent.diff().abs().sum())
    
    if total_path == 0:
        return 'trading_range'
    
    efficiency = net_change / total_path
    
    if efficiency > trend_threshold:
        return 'trending'
    elif efficiency < trend_threshold * 0.5:
        return 'trading_range'
    return 'mixed'


def assess_signals(
    closes: pd.Series,
    signals: List[OBOSExitSignal],
    forward_bars: int = 10,
    reversal_pct: float = 1.5
) -> ExitSignalAssessment:
    """
    Assess the quality of OB/OS exit signals.
    
    Checks whether price actually reversed after each signal
    (good exit) or continued in the same direction (premature exit).
    
    Parameters
    ----------
    closes : pd.Series
        Closing prices.
    signals : list of OBOSExitSignal
        Generated exit signals.
    forward_bars : int
        How many bars forward to check for reversal.
    reversal_pct : float
        Minimum percentage move against the signal to count
        as a "good exit."
        
    Returns
    -------
    ExitSignalAssessment
    """
    regime = detect_regime(closes)
    good = 0
    premature = 0
    
    for sig in signals:
        if sig.index + forward_bars >= len(closes):
            continue
        
        future = closes.iloc[sig.index:sig.index + forward_bars + 1]
        
        if sig.signal_type == 'exit_long':
            # Good exit if price drops after OB signal
            max_drop = (sig.price - float(future.min())) / sig.price * 100
            if max_drop >= reversal_pct:
                good += 1
            else:
                premature += 1
        else:
            # Good exit if price rises after OS signal
            max_rise = (float(future.max()) - sig.price) / sig.price * 100
            if max_rise >= reversal_pct:
                good += 1
            else:
                premature += 1
    
    warning = ""
    if regime == 'trending':
        warning = (
            "WARNING: Market is trending. Schwager says oscillator exits "
            "'will fail miserably during strong trending phases.' "
            "Consider using trailing stops instead."
        )
    
    return ExitSignalAssessment(
        regime=regime,
        total_signals=len(signals),
        premature_exits=premature,
        good_exits=good,
        regime_warning=warning,
    )


def threshold_tradeoff_analysis(
    closes: pd.Series,
    rsi: pd.Series,
    thresholds: List[Tuple[float, float]] = None
) -> pd.DataFrame:
    """
    Analyze the tradeoff between different OB/OS thresholds.
    
    Schwager: "The more extreme the selected threshold levels,
    the closer the signals will be to market turning points,
    but the greater the number of such points that will be missed."
    
    Parameters
    ----------
    closes : pd.Series
        Closing prices.
    rsi : pd.Series
        Pre-calculated RSI.
    thresholds : list of (OB, OS) tuples
        Threshold pairs to compare. Defaults to Schwager's examples.
        
    Returns
    -------
    pd.DataFrame
        Comparison table of signal counts and quality.
    """
    if thresholds is None:
        thresholds = [
            (70, 30),  # Standard
            (75, 25),  # Tighter
            (80, 20),  # Most extreme
        ]
    
    results = []
    for ob, os_t in thresholds:
        signals = generate_exit_signals(closes, rsi, ob, os_t)
        assessment = assess_signals(closes, signals)
        results.append({
            'OB/OS': f"{ob}/{os_t}",
            'Total signals': assessment.total_signals,
            'Good exits': assessment.good_exits,
            'Premature': assessment.premature_exits,
            'Hit rate': f"{assessment.hit_rate:.0%}",
            'Regime': assessment.regime,
        })
    
    return pd.DataFrame(results)


